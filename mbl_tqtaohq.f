C     MBL/TQTAOHQ V0.1
C     THESE PLATES ARE FORTRAN.  NOT DASHBOARDS.
C     COMMITTED IS NOT A TOKEN.  IDLE IS NOT A TOKEN.
C     0.743 IS A PARAMETER.  THERE IS NO SETTER.
C     BAND IS AN INTEGER TOKEN.  IT IS NOT A WIDTH.
C     TREAD IS THE LABEL PATH 2, 1, 3.  NOT ARRIVAL ORDER.
C     TRUST, FANO, AND VNAINF ARRIVE AS INPUTS.
C     THE COLOR LINE IS A MASK.  IT IS NOT AN IF.
C     NO TIMER.  NO POLL.  NO PREVENT-GATE.
C     A MISSING WEAKNESS STOPS AT INGRESS.  IT IS NOT DEFAULTED.
      PROGRAM MBL
      IMPLICIT NONE
      REAL FLOOR
      INTEGER REGISTERED, PENDING, CRITICAL
      INTEGER BAND, P00, P01, P10, P11
      INTEGER TRUSTOK, FANO, VNAINF, WEAK
      INTEGER MASK, CYAN, AMBER, RED, COLOR, STATE
      PARAMETER (FLOOR = 0.743)
      PARAMETER (REGISTERED = 1, PENDING = 2, CRITICAL = 3)
      PARAMETER (CYAN = 1, AMBER = 2, RED = 3)
      PARAMETER (BAND = 0)
      PARAMETER (P00 = 0, P01 = 1, P10 = 2, P11 = 3)
C
C     INPUTS.  NOT MEASURED HERE.  FLOOR IS NOT READ.
      TRUSTOK = 1
      FANO    = 1
      VNAINF  = 1
      WEAK    = 1
      IF (WEAK .EQ. 0) STOP 1
      IF (VNAINF .EQ. 0) TRUSTOK = 0
C
C     SELECTION.  MULTIPLY AND MASK.  VNAINF DOES NOT STOP THE RUN.
      COLOR = CYAN * TRUSTOK * FANO
     +      + AMBER * (1 - TRUSTOK) * FANO
     +      + RED * (1 - FANO)
      MASK = -TRUSTOK
      STATE = IAND(REGISTERED, MASK) + IAND(PENDING, NOT(MASK))
      STATE = STATE * FANO + CRITICAL * (1 - FANO)
C
C     TREAD.  UNCONDITIONAL LABEL WALK.  2, THEN 1, THEN 3.
      GO TO 2
    1 CONTINUE
      GO TO 3
    2 CONTINUE
      GO TO 1
    3 CONTINUE
C
      WRITE (6, 900) STATE, COLOR, BAND, FLOOR
  900 FORMAT ('REGISTER', 1X, I1, 1X, 'COLOR', 1X, I1, 1X,
     +        'BAND', 1X, I1, 1X, 'FLOOR', 1X, F5.3)
      STOP
      END
